# Run inside Blender (Scripting tab -> Open -> export_track.py -> Run Script).
# Writes track_points.js next to the .blend file.
#
# Coordinate mapping (Blender top view -> WebGL ground plane):
#   Blender X  ->  x
#   Blender Y  ->  -z   (WebGL's y is "up", and -z is "north" on screen)

import bpy

obj = bpy.context.active_object
if obj is None or obj.type != 'CURVE':
    obj = next(o for o in bpy.data.objects if o.type == 'CURVE')

mw = obj.matrix_world

# Optional: the reference image empty, so we can also export image-space UVs
# (u: 0 = left edge -> 1 = right edge, v: 0 = top row -> 1 = bottom row).
ref = next((o for o in bpy.data.objects
            if o.type == 'EMPTY' and o.empty_display_type == 'IMAGE' and o.data), None)
if ref:
    iw, ih = ref.data.size
    m = max(iw, ih)
    w = ref.empty_display_size * iw / m
    h = ref.empty_display_size * ih / m
    ox, oy = ref.empty_image_offset
    ref_inv = ref.matrix_world.inverted()

def xz(v):
    p = mw @ v
    return f"[{p.x:.3f}, {-p.y:.3f}]"

def uv(v):
    local = ref_inv @ (mw @ v)
    u = (local.x - ox * w) / w
    vv = 1 - (local.y - oy * h) / h
    return f"[{u:.5f}, {vv:.5f}]"

lines, uv_lines = [], []
for spline in obj.data.splines:
    pts = spline.bezier_points
    n = len(pts)
    count = n if spline.use_cyclic_u else n - 1
    for i in range(count):
        a, b = pts[i], pts[(i + 1) % n]
        pts4 = (a.co, a.handle_right, b.handle_left, b.co)
        lines.append("  [" + ", ".join(xz(q) for q in pts4) + "],")
        if ref:
            uv_lines.append("  [" + ", ".join(uv(q) for q in pts4) + "],")

js = f"""// Auto-generated by export_track.py from monzabezier.blend. Don't edit by hand:
// change the curve in Blender and re-run the script instead.
//
// Each segment is one cubic Bezier: [P0, P1, P2, P3], each point is [x, z]
// on the ground plane (y = 0). Segment i's P3 == segment i+1's P0.

const TRACK_SEGMENTS = [
{chr(10).join(lines)}
];

// Same segments in reference-image space ({ref.name if ref else "no image found"}):
// u = 0..1 left->right, v = 0..1 top->bottom (v matches image rows).
// Multiply by your grid's cols/rows to line the track up with the cubes.
const TRACK_SEGMENTS_UV = [
{chr(10).join(uv_lines)}
];

// Point on segment `seg` at t in [0, 1].
function bezierPoint(seg, t) {{
  const [p0, p1, p2, p3] = seg;
  const u = 1 - t;
  const a = u * u * u, b = 3 * u * u * t, c = 3 * u * t * t, d = t * t * t;
  return [
    a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0],
    a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1],
  ];
}}

// The whole track as a list of [x, z] points, `steps` samples per segment.
function sampleTrack(steps = 32) {{
  const out = [];
  for (const seg of TRACK_SEGMENTS) {{
    for (let i = 0; i < steps; i++) out.push(bezierPoint(seg, i / steps));
  }}
  return out;
}}
"""

path = bpy.path.abspath("//track_points.js")
with open(path, "w") as f:
    f.write(js)
print(f"Wrote {len(lines)} segments to {path} (reference image: {ref.name if ref else None})")
